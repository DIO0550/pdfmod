// 繰り返しコード 18（符号長 0 を最大 138 個）を含む符号長列のブロックを展開できることを確認する。
#[test]
fn code_length_repeat_18_fills_long_runs_of_zero() {
    // 同じ符号長列を繰り返しコード 18 で表した版。105..=255 の 151 個の 0 が
    // 138 個 + 13 個に分かれ、上限いっぱいの繰り返しを含む
    let input = [
        0x78, 0x01, 0x05, 0xC0, 0x01, 0x0D, 0x00, 0x00, 0x04, 0x00, 0xB0, 0xAC, 0x00, 0xFD, 0x13,
        0x7C, 0x91, 0xD5, 0xB3, 0xF7, 0x00, 0x0E, 0x00, 0x03, 0x25,
    ];

    assert_eq!(decode_zlib_ok(&input), b"abcdefgh");
}

// HLIT=286 / HDIST=30（シンボルをほぼ使い切る）動的ブロックを展開できることを確認する。
#[test]
fn maximum_symbol_counts_are_accepted() {
    // リテラル／長さ符号 286 個（符号長 8 が 226 個・9 が 60 個）と
    // 距離符号 30 個（符号長 4 が 2 個・5 が 28 個）を宣言したブロック。
    // 本体はリテラル 'a' + 長さ 3 / 距離 1 の後方参照
    let input = [
        0x78, 0x01, 0xED, 0x1D, 0x01, 0x20, 0x10, 0x30, 0x0C, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80, 0xAA, 0xAA, 0xAA, 0xAA, 0xAA, 0xAA, 0xAA, 0xAA,
        0xAA, 0xAA, 0xAA, 0xAA, 0xAA, 0xAA, 0xAA, 0xED, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0x0D, 0x1F, 0xC3, 0x23, 0x03, 0xCE, 0x01, 0x85,
    ];

    assert_eq!(decode_zlib_ok(&input), b"aaaa");
}

// 繰り返しが符号長列の残りを超える入力が InvalidCodeLengthRepeat になることを確認する。
#[test]
fn repeat_beyond_length_list_is_rejected() {
    // HLIT=257 / HDIST=1（符号長は 258 個）に対し、繰り返しコード 18 で
    // 138 個の 0 を 2 回埋めようとする（276 > 258）
    let input = [0x78, 0x01, 0x05, 0x00, 0x80, 0xE4, 0xFF, 0x1F];

    assert_eq!(
        decode_zlib_err(&input),
        FlateErrorKind::InvalidCodeLengthRepeat
    );
}

// 符号長符号の集合が過剰な入力が OversubscribedHuffman になることを確認する。
#[test]
fn oversubscribed_code_length_code_is_rejected() {
    // HCLEN=4 の 4 個すべてに符号長 1 を与えており、1 ビット符号が 4 つになる
    let input = [0x78, 0x01, 0x05, 0x00, 0x92, 0x04];

    assert_eq!(
        decode_zlib_err(&input),
        FlateErrorKind::OversubscribedHuffman
    );
}
