// 繰り返しコード 16（直前の符号長を複製）を含む符号長列のブロックを展開できることを確認する。
#[test]
fn code_length_repeat_16_duplicates_previous_length() {
    // 手組みの動的ブロック。'a'..'h' の 8 シンボルが符号長 4 で連続するため、
    // その区間だけを繰り返しコード 16 で表し、符号長 0 は 1 個ずつ書き出している
    let input = [
        0x78, 0x01, 0x05, 0xC0, 0x07, 0x04, 0x00, 0x00, 0x08, 0x00, 0x30, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFD, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x13, 0x59,
        0x3D, 0x7B, 0x0F, 0x0E, 0x00, 0x03, 0x25,
    ];

    assert_eq!(decode_zlib_ok(&input), b"abcdefgh");
}

// 繰り返しコード 17（符号長 0 を 3〜10 個）を含む符号長列のブロックを展開できることを確認する。
