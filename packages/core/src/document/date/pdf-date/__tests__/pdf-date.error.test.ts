import { expect, test } from "vitest";
import { none } from "../../../../utils/option";
import { parsePdfDate } from "../../pdf-date";

test.each([
  ["20230101"],
  ["D:abcd"],
  ["D:20231345"],
  ["D:20230231"],
  ["D:20230229"],
  ["D:20230231000000+09'00'"],
  ["D:20230101246000"],
  ["D:20230101000061"],
  ["D:20230101000000+25'00'"],
  ["D:0050"],
  ["D:0999"],
  ["D:00500101"],
  ["D:10000"],
  ["D:"],
  ["D:202"],
  ["D:2023011"],
  ["D:2023+"],
  ["D:20230101000000+09'00'extra"],
  ["D:20230101000000+09'00"],
  ["D:20260001"],
  ["D:20260100"],
  ["D:20260101000000+09'60'"],
  ["D:20260101000000+09'99'"],
  ["D:20260230"],
  ["D:20260431"],
  ["D:20260230000000Z"],
  ["D:20260431000000Z"],
])("不正な PDF 日時 %s は none を返す", (raw) => {
  expect(parsePdfDate(raw)).toEqual(none);
});

