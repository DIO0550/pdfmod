/** 100 = 100%（百分率の基準値）。 */
const PERCENT = 100;

/** 数値変換ユーティリティ。単位変換・比率変換など、定数除算で表される頻出変換を提供する。 */
export const MathEx = {
  /**
   * 百分率の数値を倍率（1.0 = 100%）に変換する（`n / 100`）。
   *
   * PDF horizontal scaling (§9.3.4) など「100 = 等倍」の百分率パラメータを
   * 行列計算に渡す前に倍率へ戻すのに用いる。`fromPercent(200) === 2` のように
   * 1 を超える値や負値もそのまま通す（範囲制約なし）。
   *
   * @param n - 百分率の数値（100 = 100%）
   * @returns 倍率に変換した数値（1.0 = 等倍、2.0 = 2 倍、0.5 = 半分、…）
   */
  fromPercent: (n: number): number => n / PERCENT,
} as const;
